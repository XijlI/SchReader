#!/usr/bin/env python3
"""Mirror the browser extension's reader page + extractor into the Android app assets.

There is exactly ONE source of truth: `extension/`. The files under
`app/src/main/assets/` are generated by this script on every build (they are
gitignored), so a fix to the reader or the extractor reaches both the Chrome
extension and the phone at once.

Run from anywhere:  python3 tools/mirror.py
"""
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # android/tools
ANDROID = HERE.parent                           # android/
REPO = ANDROID.parent                           # repo root
EXT = REPO / "extension"
ASSETS = ANDROID / "app" / "src" / "main" / "assets"

# manifest.json order matters: each file extends window.SR built by the previous one
EXTRACTOR_ORDER = [
    "util.js", "meta.js", "blocks.js", "refs.js",
    "figures.js", "adapters.js", "generic.js",
]


def die(msg):
    print(f"[mirror] ERROR: {msg}")
    sys.exit(1)


def main():
    if not (EXT / "reader.html").exists():
        die(f"extension not found at {EXT}")

    reader_dst = ASSETS / "reader"
    reader_dst.mkdir(parents=True, exist_ok=True)
    for name in ("reader.html", "reader.css", "reader.js",
                 "library.html", "library.css", "library.js", "library-store.js",
                 "search.html", "search.js", "settings.html", "settings.js",
                 "theme.js"):
        shutil.copy2(EXT / name, reader_dst / name)

    # the home pages load "src/whitelist.js" by the same relative path as in the extension
    wl_dst = reader_dst / "src"
    wl_dst.mkdir(parents=True, exist_ok=True)
    shutil.copy2(EXT / "src" / "whitelist.js", wl_dst / "whitelist.js")

    fonts_src = EXT / "fonts"
    fonts_dst = reader_dst / "fonts"
    fonts_dst.mkdir(parents=True, exist_ok=True)
    for f in fonts_src.glob("*.woff2"):
        shutil.copy2(f, fonts_dst / f.name)

    parts = []
    for name in EXTRACTOR_ORDER:
        p = EXT / "src" / "extractor" / name
        if not p.exists():
            die(f"missing extractor file {p}")
        parts.append(f"/* ================= {name} ================= */\n"
                     + p.read_text(encoding="utf-8"))
    bundle = "\n".join(parts)
    (ASSETS / "extractor.bundle.js").write_text(bundle, encoding="utf-8")

    print(f"[mirror] reader + library pages + {len(list(fonts_dst.glob('*.woff2')))} fonts "
          f"-> {reader_dst.relative_to(ANDROID)}")
    print(f"[mirror] extractor bundle {len(bundle):,} bytes "
          f"-> {(ASSETS / 'extractor.bundle.js').relative_to(ANDROID)}")


if __name__ == "__main__":
    main()
